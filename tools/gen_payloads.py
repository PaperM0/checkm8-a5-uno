"""Generate payloads.h: three SoC payloads side by side, no #ifdef.

Reads the upstream constants.h (a1exdandy), strips the preprocessor selection
and emits one array per CPID plus the shared `overwrite` block.
"""
import re
import sys
from pathlib import Path

src = Path(sys.argv[1])
dst = Path(sys.argv[2])
txt = src.read_text(encoding="utf-8", errors="replace")

# split on  "#if defined X" / "#elif defined X"
parts = re.split(r"#(?:if|elif)\s+defined\s+(\w+)", txt)
sections = {}
for i in range(1, len(parts), 2):
    sections[parts[i]] = parts[i + 1]


def bytes_of(body):
    body = body.split("};")[0]
    return [int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{2})", body)]


def padding_of(body):
    m = re.search(r"int\s+padding\s*=\s*0x([0-9a-fA-F]+)\s*;", body)
    return int(m.group(1), 16) if m else None


order = ["A5_8942", "A5_8945", "A5_8940"]
cpid = {"A5_8942": "8942", "A5_8945": "8945", "A5_8940": "8940"}

out = []
out.append("/* generated by gen_payloads.py - do not edit by hand */")
out.append("#pragma once")
out.append("#include <stdint.h>")
out.append("#include <avr/pgmspace.h>")
out.append("")

for soc in order:
    body = sections[soc]
    data = bytes_of(body)
    pad = padding_of(body)
    name = f"payload_{cpid[soc]}"
    out.append(f"static const uint16_t padding_{cpid[soc]} = 0x{pad:04x};")
    out.append(f"static const uint8_t {name}[] PROGMEM = {{")
    for i in range(0, len(data), 12):
        chunk = ", ".join(f"0x{b:02x}" for b in data[i:i + 12])
        out.append(f"    {chunk},")
    out.append("};")
    out.append(f"static const uint16_t {name}_len = sizeof({name});")
    out.append("")

# the shared overwrite buffer lives after the #endif
tail = txt.split("#endif", 1)[1]
ow = bytes_of(tail.split("overwrite")[1])
out.append("static const uint8_t overwrite[] PROGMEM = {")
for i in range(0, len(ow), 12):
    chunk = ", ".join(f"0x{b:02x}" for b in ow[i:i + 12])
    out.append(f"    {chunk},")
out.append("};")
out.append(f"static const uint16_t overwrite_len = sizeof(overwrite);")
out.append("")

dst.write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"wrote {dst}  ({dst.stat().st_size} bytes)")
for soc in order:
    print(f"  {soc}: payload {len(bytes_of(sections[soc]))} B, padding 0x{padding_of(sections[soc]):04x}")
print(f"  overwrite: {len(ow)} B")
